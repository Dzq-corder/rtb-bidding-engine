-- 【踩坑 1】直接分区会失败
--   ALTER TABLE bid_log PARTITION BY RANGE (TO_DAYS(bid_at)) (...);
--   → ERROR 1503 (HY000): A PRIMARY KEY must include all columns in the
--     table's partitioning function (prefixed columns are not considered).
--
-- 【原因】MySQL 分区表要求「每个唯一索引都必须包含分区键」。
--   原因很实在：分区之间没有数据约束，A 行和 B 行如果 request_id 相同
--   却落在不同分区，唯一索引就检测不到重复 —— 幂等键会失效。
--   M6 的对账幂等正是靠 uk_request，所以这条不能绕过。
--
-- 【踩坑 2】改主键时要注意 AUTO_INCREMENT
--   InnoDB 要求 AUTO_INCREMENT 列必须是<b>某个索引的第一列</b>。
--   (id, bid_at) 满足；写成 (bid_at, id) 会报：
--     ERROR 1075 (42000): Incorrect table definition;
--     there can be only one auto column and it must be defined as a key
--   注意这条<b>不是分区特有的</b>，非分区表写 (bid_at, id) 一样报错。
--   （我一开始凭印象写的是 ERROR 1470，拿临时表实测才发现是 1075，
--     报错文案也会直接把规则说出来——比记错误码靠谱。）
--
-- 【踩坑 3】分区键不能在 WHERE 里套函数
--   WHERE TO_DAYS(bid_at) = ... 不会触发分区裁剪（裁剪只认列上的比较）。
--   必须写 WHERE bid_at >= ... AND bid_at < ...
--
-- ---------------------------------------------------------------------
-- 【执行】把索引改对 + 一次性建好 92 个分区
