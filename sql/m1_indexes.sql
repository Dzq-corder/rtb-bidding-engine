-- =====================================================================
-- RTB 投放引擎 · M1 候选检索的索引方案
-- =====================================================================
-- 为什么要有这个文件：
--   M1 需要一个「未优化」的对照基线，但同时又要求候选集落在 100~200 条
--   （造数方案 §2.4）。这两个要求有冲突：
--     - 候选集要小  -> 必须有多维定向条件，否则类目级粗筛出 8.5 万条
--     - 检索要慢    -> ad 表不能有索引，必须保持 type=ALL
--   解法：ad 不建索引（承担「慢」），ad_target 建索引（承担「筛得准」）。
--
-- 验证口径（M8 要拿这组做对照，不要在 M8 之前改动本文件）：
--   EXPLAIN 应显示 ad 表 type=ALL、key=NULL
-- =====================================================================

-- ---------------------------------------------------------------------
-- ad_target：定向条件倒排索引
--
-- 索引 (dim_type, dim_value, ad_id) 覆盖三个用途：
--   1. 按维度取值定位候选（dim_type + dim_value 等值前缀）
--   2. JOIN 时从 ad_id 回表（覆盖索引，避免回 ad_target 主键）
--   3. M2 改为内存位集后，此索引即可撤掉——它本来就是 M1 的过渡产物
-- ---------------------------------------------------------------------
CREATE INDEX idx_dim_lookup ON ad_target (dim_type, dim_value, ad_id);

