-- ============================================================================
-- 演示数据修复 · M9
--
-- 【发现的真实问题】
-- 演示手册第 5 步是全场高潮一：「把 A 的预算改成 20，连刷 15~20 次，
-- 看到 A 从广告位消失」。但 M9 实测发现这个前提<b>不成立</b>：
--
--   ad_88001 的出价只有 1.28 元，而在演示手册用的画像
--   （地域 2301 / 25-30 岁 / 男）下，出价高于它的广告有 280 条。
--   换句话说 <b>A 从来没有赢过任何一次竞价</b>，
--   「刷到 A 消失」这个现象根本不会发生——它一开始就「消失」了。
--
-- 手册里还写着「A 出价 3.2 排第一」，说明当初设计演示时
-- 心里假定它是最高价，实际造数（对数正态长尾）把它压到了尾部。
-- <b>造数脚本是按分布生成的，没有为「演示需要它赢」这个要求留过约束。</b>
--
-- 【修法】
-- 把 A 的出价抬到它在自己画像下的最高水位之上，
-- 并给它挂一个更窄的画像（只投演示用到的那几个地域），
-- 这样它在演示流量里就是稳定的赢家，预算耗尽的现象才演得出来。
--
-- 【为什么不用「挑一个当前最高价的广告当 A」】
-- 那样每次重建环境 A 都会变，截图与讲稿对不上。
-- 固定 ID + 固定出价，可复现是这一层的硬要求。
--
-- 【幂等】
-- 可重复执行，不会把已经修好的数据改坏。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1. 抬高出价：从 1.28 提到 18.00
--
-- 【为什么是 18 而不是更高】
-- 第一版抬到 45，结果单次扣费涨到 17.44 元——
-- 因为**二价扣的是次高价 + 0.01，与胜出者自己的出价无关**。
-- 演示画像下第 2 名出价 17.43，所以无论 A 报 18 还是 45，
-- 单次都要扣 17.44 元，抬高价只是在虚张声势。
--
-- 18.00 刚好压过次高 17.43，留 0.01 的安全余量。
-- 真正的杠杆在预算，见下面第 3 步。
-- ---------------------------------------------------------------------------
UPDATE ad SET bid = 18.00 WHERE id = 88001;

-- ---------------------------------------------------------------------------
-- 2. 收窄画像：只保留演示会用的两个地域
--
-- 【为什么要收窄而不是只抬价】
-- 只抬价的话，A 会在它所有 10 个定向项的交集里都成赢家，
-- 而演示流量只用到其中 2 个地域——多出来的赢面只会让「消失」来得更慢，
-- 因为每次扣费都比需要的多。
--
-- 保留 2301 / 4308：前者是手册第 3 步示例画像的地域，
-- 后者给「换个画像 A 也在」留个备份。
-- ---------------------------------------------------------------------------
DELETE FROM ad_target WHERE ad_id = 88001 AND dim_type = 1
  AND dim_value NOT IN ('2301', '4308');

-- 年龄段保留 25-30（手册示例画像）与 41-45（次备份）
DELETE FROM ad_target WHERE ad_id = 88001 AND dim_type = 2
  AND dim_value NOT IN ('25-30', '41-45');

-- 性别只留 male：手册所有示例请求都是 gender=1
DELETE FROM ad_target WHERE ad_id = 88001 AND dim_type = 3
  AND dim_value <> 'male';

-- 兴趣/系统维度留着不影响求交（链路只按地域+年龄+性别求交），
-- 但它们在演示里没用，留着会让 /admin/ads 页面上的定向列表显得杂乱。
DELETE FROM ad_target WHERE ad_id = 88001 AND dim_type IN (4, 5, 6);

-- 地域收窄后必须补上，否则 A 会被地域 2301 之外的流量投到
--
-- ⚠️ 【踩过的坑：直接 INSERT 不幂等】
-- 第一版这里写的是普通 INSERT，结果脚本重跑一次就多一份重复定向：
-- ad_target 只有 PRIMARY KEY(id)，没有 (ad_id,dim_type,dim_value) 唯一约束，
-- 重复插入不会报错，只会静静多出一份。
-- 而倒排索引求交时同一条广告会被算两次，导致候选集虚高、
-- 「数一数有几条比它贵」的自检结果也不可信。
--
-- 修法：用 INSERT ... SELECT ... WHERE NOT EXISTS，
-- 让「补齐缺失项」这个动作本身可重复执行。
-- 这比在脚本开头写 DELETE 干净——后者会把用户手工加的定向也清掉。
INSERT INTO ad_target (ad_id, dim_type, dim_value)
SELECT 88001, 1, '2301' FROM DUAL
  WHERE NOT EXISTS (SELECT 1 FROM ad_target WHERE ad_id=88001 AND dim_type=1 AND dim_value='2301');

INSERT INTO ad_target (ad_id, dim_type, dim_value)
SELECT 88001, 1, '4308' FROM DUAL
  WHERE NOT EXISTS (SELECT 1 FROM ad_target WHERE ad_id=88001 AND dim_type=1 AND dim_value='4308');

INSERT INTO ad_target (ad_id, dim_type, dim_value)
SELECT 88001, 2, '25-30' FROM DUAL
  WHERE NOT EXISTS (SELECT 1 FROM ad_target WHERE ad_id=88001 AND dim_type=2 AND dim_value='25-30');

INSERT INTO ad_target (ad_id, dim_type, dim_value)
SELECT 88001, 2, '41-45' FROM DUAL
  WHERE NOT EXISTS (SELECT 1 FROM ad_target WHERE ad_id=88001 AND dim_type=2 AND dim_value='41-45');

INSERT INTO ad_target (ad_id, dim_type, dim_value)
SELECT 88001, 3, 'male' FROM DUAL
  WHERE NOT EXISTS (SELECT 1 FROM ad_target WHERE ad_id=88001 AND dim_type=3 AND dim_value='male');

-- ---------------------------------------------------------------------------
-- 3. 预算回 300，状态回在投
--
-- 【为什么是 300 而不是手册原先写的 20】
-- 单次扣 17.44 元是二价规则决定的，改不动（见上面第 1 步的说明）。
-- 手册第 5 步要「连刷 15~20 次看到 A 逐渐消失」，
-- 于是预算必须 ≥ 17.44 × 15 ≈ 262 元才有足够扣减次数。
-- 取 300 元 ≈ 17 次，正好落在手册要的区间内。
--
-- ⚠️ 原来的 20 元会让 A **一次就扣掉 87%**，
-- 第二次刷新直接余额不足——不是「逐渐消失」，是「刷新两次就没了」。
-- 现场看会以为功能坏了，而排查方向会完全跑偏。
--
-- 若确实要小预算演示，把 18 改成 45 也没用：
-- 扣的永远是次高价 17.44。要降低单次扣费只能换竞争更少的画像。
-- ---------------------------------------------------------------------------
UPDATE ad
SET daily_budget = 300.00,
    status = CASE WHEN status = 3 THEN 1 ELSE status END
WHERE id = 88001;

