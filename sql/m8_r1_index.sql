-- 靶子查询（与 TuneMapper.dashGroupByResult 完全一致）：
--   SELECT has_ad, COUNT(*) AS cnt
--   FROM bid_log
--   WHERE slot_code = ? AND bid_at >= ? AND bid_at < ?
--   GROUP BY has_ad
--
-- ---------------------------------------------------------------------
-- 三份执行计划（全部实测，见 metrics/M8-r1-index.md）
-- ---------------------------------------------------------------------
-- A. 无索引：
--    type=ALL   rows=9,632,950  filtered=1.11
--    Extra = Using where; Using temporary
--    实测 min 7,346 ms
--
-- B. 第一版 (slot_code, has_ad, bid_at)：
--    type=ref   key_len=130   rows=5,071,302   filtered=11.11
--    Extra = Using where; Using index          ← 临时表消失了
--    实测 min 1,683 ms
--
-- C. 第二版 (slot_code, bid_at, has_ad)  ← 最终采用：
--    type=range  key_len=137  rows=68,172  filtered=100.00
--    Extra = Using where; Using index; Using temporary
--    实测 min 43 ms
--
-- ---------------------------------------------------------------------
-- 为什么第一版是错的（这段是最值得讲的部分）
-- ---------------------------------------------------------------------
-- 第一版把 has_ad 放在 bid_at 前面，理由是「GROUP BY has_ad 能用上索引有序性」。
-- 这个理由本身没错——B 的 Extra 里 Using temporary 确实消失了。
--
-- 但它踩了最左前缀的另一条规则：
--   **MySQL 遇到第一个范围列之后，就停止使用后面的索引列。**
-- 索引 (slot_code, has_ad, bid_at) 里，has_ad 在 WHERE 中没有等值条件
-- （它在 GROUP BY 里），于是 bid_at 这个范围条件前面出现了一个「空洞」，
-- 范围定位用不上，只能退化成 ref——
-- 证据就是 key_len=130：130 = varchar(32) utf8mb4 的 32*4+2，
-- 正好只覆盖 slot_code 一列，bid_at 一个字节都没用上。
--
-- 后果：整个广告位的 340 万条索引项全部扫一遍（rows=5,071,302），
-- 而窗口内真正需要的只有 3.5 万条。
--
-- 第二版把 bid_at 提到 has_ad 前面：
--   - 等值列 slot_code + 范围列 bid_at 构成连续前缀 → type=range
--   - rows 从 5,071,302 降到 68,172（约 1/74）
--   - 代价是 Using temporary 回来了（窗口内 has_ad 不再有序），
--     但总共只有 2 个分组，临时表的代价远小于少扫 500 万行
--
-- **结论：GROUP BY 的索引有序性 让位给 范围定位的选择性。**
-- 这条不是靠推理得出的，是靠 key_len=130 这个数字发现的。
--
-- ---------------------------------------------------------------------
-- 最终执行（当前库状态就是这一条）
-- ---------------------------------------------------------------------
CREATE INDEX idx_slot_time_result ON bid_log (slot_code, bid_at, has_ad);

